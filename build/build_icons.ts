import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import type {
  IconData,
  IconKeywords,
  IconNode,
} from "../plug-api/ui/icons/types.ts";
import { CORE_ICON_NAMES } from "../plug-api/ui/icons/core_names.ts";

const LUCIDE_DIR = "node_modules/lucide-static";

function kebabToPascal(name: string): string {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

export async function buildIconData(
  lucideDir: string = LUCIDE_DIR,
): Promise<{ data: IconData; keywords: IconKeywords }> {
  const icons: Record<string, IconNode> = JSON.parse(
    await readFile(join(lucideDir, "icon-nodes.json"), "utf-8"),
  );
  const keywords: IconKeywords = JSON.parse(
    await readFile(join(lucideDir, "tags.json"), "utf-8"),
  );

  // Lucide only records aliases as extra re-exports of a canonical module:
  // `export { default as CheckSquare, default as SquareCheckBig } from './icons/square-check-big.mjs'`
  const esm = await readFile(
    join(lucideDir, "dist/esm/lucide-static.mjs"),
    "utf-8",
  );
  const canonicalByPascal = new Map<string, string>();
  for (const m of esm.matchAll(
    /export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g,
  )) {
    const canonical = m[2];
    for (const part of m[1].matchAll(/default as (\w+)/g)) {
      canonicalByPascal.set(part[1], canonical);
    }
  }
  const pascalToKebab = new Map<string, string>();
  for (const name of Object.keys(icons)) {
    pascalToKebab.set(kebabToPascal(name), name);
  }

  const aliases: Record<string, string> = {};
  const { readdir } = await import("node:fs/promises");
  for (const file of await readdir(join(lucideDir, "icons"))) {
    if (!file.endsWith(".svg")) continue;
    const name = file.slice(0, -4);
    if (icons[name]) continue;
    const target = canonicalByPascal.get(kebabToPascal(name));
    if (target && icons[target]) aliases[name] = target;
  }
  return { data: { icons, aliases }, keywords };
}

export async function writeIconAssets(outDir: string): Promise<void> {
  const { data, keywords } = await buildIconData();
  await writeFile(join(outDir, "icons.json"), JSON.stringify(data));
  await writeFile(join(outDir, "icon-tags.json"), JSON.stringify(keywords));
}

/** Picks the core subset out of the full set; every core name must exist. */
export function coreSubset(data: IconData, names: readonly string[]): IconData {
  const icons: Record<string, IconNode> = {};
  const aliases: Record<string, string> = {};
  for (const name of names) {
    const canonical = data.aliases[name] ?? name;
    const node = data.icons[canonical];
    if (!node) throw new Error(`Core icon "${name}" is not a Lucide icon`);
    icons[canonical] = node;
    if (canonical !== name) aliases[name] = canonical;
  }
  for (const [alias, target] of Object.entries(data.aliases)) {
    if (icons[target]) aliases[alias] = target;
  }
  return { icons, aliases };
}

async function writeCoreModule(): Promise<void> {
  const { data } = await buildIconData();
  const core = coreSubset(data, CORE_ICON_NAMES);
  const source = `// Generated by build/build_icons.ts (npm run build:icons). Do not edit.
import type { IconData } from "./types.ts";

export const CORE_ICONS: IconData = ${JSON.stringify(core)};
`;
  await writeFile("plug-api/ui/icons/core.generated.ts", source);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeCoreModule();
  console.log("Wrote plug-api/ui/icons/core.generated.ts");
}
